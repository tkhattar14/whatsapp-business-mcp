"""
Storage for every message the group agent sees or sends.

Uses the same database as the support bot (PostgreSQL via DATABASE_URL, or the
local SQLite file), through the same Database adapter.
"""

import json
import time
from typing import Any, Dict, List, Optional

from support_bot.store import Database

_SCHEMA = """
CREATE TABLE IF NOT EXISTS group_messages (
    id          {pk},
    msg_id      TEXT UNIQUE,
    chat_id     TEXT NOT NULL,
    chat_name   TEXT,
    is_group    {int} NOT NULL DEFAULT 1,
    sender_id   TEXT,
    sender_name TEXT,
    from_me     {int} NOT NULL DEFAULT 0,
    msg_type    TEXT,
    text        TEXT,
    quoted_id   TEXT,
    mentions    TEXT,
    ts          {int} NOT NULL,
    synced      {int} NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_group_messages_chat ON group_messages(chat_id, ts);
CREATE INDEX IF NOT EXISTS idx_group_messages_unsynced ON group_messages(synced, id);

-- One row per resident issue raised in a group, from report to feedback
CREATE TABLE IF NOT EXISTS group_issues (
    id                  {pk},
    ref                 TEXT UNIQUE,
    chat_id             TEXT NOT NULL,
    chat_name           TEXT,
    resident_id         TEXT,
    resident_name       TEXT,
    reported_msg_id     TEXT,
    summary             TEXT NOT NULL,
    service_area        TEXT,
    status              TEXT NOT NULL,
    opened_at           {int} NOT NULL,
    acknowledged_at     {int},
    staff_response_at   {int},
    staff_name          TEXT,
    reminders           {int} NOT NULL DEFAULT 0,
    reminded_at         {int},
    escalated_at        {int},
    resolved_at         {int},
    resolved_by         TEXT,
    survey_sent_at      {int},
    score               {int},
    feedback            TEXT,
    closed_at           {int},
    notes               TEXT,
    synced              {int} NOT NULL DEFAULT 0,
    ack_due_at          {int},
    followups           {int} NOT NULL DEFAULT 0,
    followed_up_at      {int}
);
CREATE INDEX IF NOT EXISTS idx_group_issues_chat ON group_issues(chat_id, status);
CREATE INDEX IF NOT EXISTS idx_group_issues_unsynced ON group_issues(synced, id)
"""

# Issue statuses
OPEN = "Open"                            # reported, waiting for staff
IN_PROGRESS = "In Progress"              # a staff member has responded
AWAITING_FEEDBACK = "Awaiting Feedback"  # staff said done; resident asked for a rating
CLOSED = "Closed"                        # rating received
CLOSED_NO_FEEDBACK = "Closed - No Feedback"
ACTIVE_STATUSES = (OPEN, IN_PROGRESS, AWAITING_FEEDBACK)

# Columns added after the first release: created on databases made before them
_ADDED_ISSUE_COLUMNS = {"ack_due_at": "{int}", "followups": "{int} NOT NULL DEFAULT 0", "followed_up_at": "{int}"}


def issue_ref(issue_id: int) -> str:
    return f"MMF-G{issue_id:05d}"


class GroupStore:
    def __init__(self, target: str):
        self.db = Database(target)
        if self.db.postgres:
            schema = _SCHEMA.format(pk="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", int="BIGINT")
        else:
            schema = _SCHEMA.format(pk="INTEGER PRIMARY KEY AUTOINCREMENT", int="INTEGER")
        for statement in schema.split(";"):
            if statement.strip():
                self.db.execute(statement)
        self._add_columns()

    def _add_columns(self) -> None:
        int_type = "BIGINT" if self.db.postgres else "INTEGER"
        if self.db.postgres:
            for column, kind in _ADDED_ISSUE_COLUMNS.items():
                self.db.execute(f"ALTER TABLE group_issues ADD COLUMN IF NOT EXISTS {column} {kind.format(int=int_type)}")
            return
        existing = {r["name"] for r in self.db.query("PRAGMA table_info(group_issues)")}
        for column, kind in _ADDED_ISSUE_COLUMNS.items():
            if column not in existing:
                self.db.execute(f"ALTER TABLE group_issues ADD COLUMN {column} {kind.format(int=int_type)}")

    def close(self) -> None:
        self.db.close()

    def add_message(self, event: Dict[str, Any]) -> bool:
        """Store a message. Returns False if it was already stored (e.g. our own reply echoed back)."""
        changed = self.db.execute(
            """INSERT INTO group_messages
               (msg_id, chat_id, chat_name, is_group, sender_id, sender_name, from_me,
                msg_type, text, quoted_id, mentions, ts)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) ON CONFLICT DO NOTHING""",
            (
                event.get("id"), event["chat"], event.get("chat_name"), int(bool(event.get("is_group", True))),
                event.get("sender"), event.get("sender_name"), int(bool(event.get("from_me"))),
                event.get("type") or "text", event.get("text") or "", event.get("quoted_id"),
                json.dumps(event.get("mentions") or []), int(event.get("timestamp") or time.time()),
            ),
        )
        return changed == 1

    def recent(self, chat_id: str, limit: int) -> List[Dict[str, Any]]:
        """The last `limit` messages in a chat, oldest first."""
        rows = self.db.query(
            "SELECT * FROM group_messages WHERE chat_id = ? ORDER BY ts DESC, id DESC LIMIT ?", (chat_id, limit)
        )
        return list(reversed(rows))

    def last_reply_at(self, chat_id: str) -> Optional[int]:
        row = self.db.one("SELECT MAX(ts) AS ts FROM group_messages WHERE chat_id = ? AND from_me = 1", (chat_id,))
        return row["ts"] if row else None

    def staff_message_since(self, chat_id: str, since: int, is_staff) -> Optional[Dict[str, Any]]:
        """The first message from staff in a chat after `since` (is_staff(message) decides)."""
        rows = self.db.query(
            "SELECT * FROM group_messages WHERE chat_id = ? AND ts > ? AND from_me = 0 ORDER BY ts, id LIMIT 200",
            (chat_id, since),
        )
        return next((m for m in rows if is_staff(m)), None)

    def list_messages(self, chat_id: Optional[str] = None, limit: int = 200) -> List[Dict[str, Any]]:
        if chat_id:
            return self.db.query(
                "SELECT * FROM group_messages WHERE chat_id = ? ORDER BY ts DESC, id DESC LIMIT ?", (chat_id, limit)
            )
        return self.db.query("SELECT * FROM group_messages ORDER BY ts DESC, id DESC LIMIT ?", (limit,))

    # ================================
    # ISSUES
    # ================================

    def create_issue(
        self, chat_id: str, chat_name: Optional[str], resident_id: Optional[str], resident_name: Optional[str],
        reported_msg_id: Optional[str], summary: str, service_area: Optional[str], opened_at: Optional[int] = None,
    ) -> Dict[str, Any]:
        with self.db.transaction():
            row = self.db.one(
                """INSERT INTO group_issues (chat_id, chat_name, resident_id, resident_name, reported_msg_id,
                       summary, service_area, status, opened_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?) RETURNING id""",
                (chat_id, chat_name, resident_id, resident_name, reported_msg_id, summary, service_area, OPEN,
                 int(opened_at or time.time())),
            )
            self.db.execute("UPDATE group_issues SET ref = ? WHERE id = ?", (issue_ref(row["id"]), row["id"]))
            return self.db.one("SELECT * FROM group_issues WHERE id = ?", (row["id"],))

    def get_issue(self, ref: str) -> Optional[Dict[str, Any]]:
        return self.db.one("SELECT * FROM group_issues WHERE ref = ?", ((ref or "").strip().upper(),))

    def update_issue(self, ref: str, **fields: Any) -> Dict[str, Any]:
        fields["synced"] = 0  # changed -> write it to Excel again
        assignments = ", ".join(f"{column} = ?" for column in fields)
        self.db.execute(f"UPDATE group_issues SET {assignments} WHERE ref = ?", (*fields.values(), ref))
        return self.get_issue(ref)

    def active_issues(self, chat_id: Optional[str] = None) -> List[Dict[str, Any]]:
        marks = ", ".join("?" for _ in ACTIVE_STATUSES)
        if chat_id:
            return self.db.query(
                f"SELECT * FROM group_issues WHERE chat_id = ? AND status IN ({marks}) ORDER BY id",
                (chat_id, *ACTIVE_STATUSES),
            )
        return self.db.query(f"SELECT * FROM group_issues WHERE status IN ({marks}) ORDER BY id", ACTIVE_STATUSES)

    def list_issues(self, limit: int = 500) -> List[Dict[str, Any]]:
        return self.db.query("SELECT * FROM group_issues ORDER BY id DESC LIMIT ?", (limit,))

    def unsynced_issues(self, limit: int = 50) -> List[Dict[str, Any]]:
        return self.db.query("SELECT * FROM group_issues WHERE synced = 0 ORDER BY id LIMIT ?", (limit,))

    def mark_issues_synced(self, refs_and_versions: List[Dict[str, Any]]) -> None:
        for issue in refs_and_versions:
            # Only if unchanged since it was read, so an update made meanwhile is synced next time
            self.db.execute(
                "UPDATE group_issues SET synced = 1 WHERE ref = ? AND status = ? AND COALESCE(reminders, 0) = ?"
                " AND COALESCE(score, -1) = ? AND COALESCE(staff_response_at, 0) = ? AND COALESCE(escalated_at, 0) = ?"
                " AND COALESCE(acknowledged_at, 0) = ? AND COALESCE(followups, 0) = ?",
                (issue["ref"], issue["status"], issue["reminders"] or 0, -1 if issue["score"] is None else issue["score"],
                 issue["staff_response_at"] or 0, issue["escalated_at"] or 0, issue.get("acknowledged_at") or 0,
                 issue.get("followups") or 0),
            )

    def chats(self) -> List[Dict[str, Any]]:
        return self.db.query(
            """SELECT chat_id, MAX(chat_name) AS chat_name, COUNT(*) AS messages,
                      SUM(from_me) AS replies, MAX(ts) AS last_ts
               FROM group_messages GROUP BY chat_id ORDER BY last_ts DESC"""
        )
